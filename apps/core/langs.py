"""Короткие ярлыки локалей для пилюль переключателей языка.

Фидбэк владельца 2026-07-31: «Украинский обозначение не uk а ua». Показываем
**UA**, но ВНУТРЕННИЙ код остаётся ``uk``: это ISO 639-1 для украинского языка, и
на нём завязаны каталог ``locale/uk/LC_MESSAGES/``, ``.po``/``.mo``,
``settings.LANGUAGES``, сохранённые у тенантов ``active_locales`` и заголовок
``Accept-Language`` браузеров. ``ua`` — код СТРАНЫ, не языка; переименование
обнулило бы переводы и языковые настройки существующих тенантов.
"""

# code -> ярлык, если он отличается от простого верхнего регистра
BADGES = {"uk": "UA"}


def badge(code) -> str:
    """Ярлык локали для переключателя: DE / EN / UA / …"""
    code = (code or "").strip()
    return BADGES.get(code, code.upper())
