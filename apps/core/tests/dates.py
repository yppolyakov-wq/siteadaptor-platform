"""Даты для замков, которым нужна дата В БУДУЩЕМ (заезд, бронь, наличие).

Жёсткое `date(2026, 10, 1)  # в будущем относительно «сегодня»` — бомба с часовым
механизмом: 1 октября 2026 замки календаря номера покраснели (фикс 2026-10-01), 2 октября
— замки buy-box номера (дата заезда стала прошлой, форма брони не выводится по замыслу).
Код при этом был верен. База дат файла поэтому СЧИТАЕТСЯ от сегодня.
"""

from datetime import date


def future_month_start(months: int = 2) -> date:
    """1-е число месяца через `months` месяцев от сегодня.

    `date.today()`, а не `timezone.localdate()`: модуль импортируется до того, как
    конкретный тест настроит часовой пояс, а для «месяц в будущем» разница в сутки
    не значима. Расчёт идёт через число месяцев — переход через год и февраль не
    требуют особых случаев.
    """
    today = date.today()
    y, m = divmod(today.year * 12 + (today.month - 1) + months, 12)
    return date(y, m + 1, 1)
