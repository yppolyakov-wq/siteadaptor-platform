"""Минимизация персональных данных в свободном тексте (DSGVO).

Регулярки ловят e-mail, IBAN и телефон (7+ цифр); имена и адреса — нет, поэтому
вызывающий код передаёт наружу только нужные поля. Общий хелпер: журнал поиска
города (T-8.21) и ИИ-слой (AI-0) чистят текст одинаково."""

import re

_EMAIL = re.compile(r"\S+@\S+")
_IBAN = re.compile(r"\b[A-Z]{2}\d{2}(?:[ ]?[A-Z0-9]{4}){3,7}(?:[ ]?[A-Z0-9]{1,4})?\b", re.I)
# Телефон: 7+ цифр с любыми разделителями (пробел, -, /, ., скобки); PLZ (5) и цены целы.
_PHONE = re.compile(r"\(?\+?[\d][\d \-/().]{5,}\d")


def scrub(text: str) -> str:
    """Убрать из свободного текста то, что похоже на персональные данные.

    Регистронезависимо (IBAN в нижнем регистре тоже ловится)."""
    text = _EMAIL.sub("‹email›", text or "")
    text = _IBAN.sub("‹iban›", text)
    return _PHONE.sub(
        lambda m: "‹nummer›" if sum(c.isdigit() for c in m.group()) >= 7 else m.group(), text
    )
